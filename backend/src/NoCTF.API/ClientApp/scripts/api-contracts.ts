import { existsSync, readFileSync, readdirSync, unlinkSync } from 'node:fs'
import { resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const clientRoot = fileURLToPath(new URL('..', import.meta.url))
const backendRoot = resolve(clientRoot, '../../..')
const repositoryRoot = resolve(backendRoot, '..')
const hostRoot = resolve(backendRoot, 'src/NoCTF.Host')
const output = resolve(clientRoot, 'app/api')
const document = resolve(backendRoot, 'artifacts/openapi/v1.json')
const mode = process.argv[2]
if (!['generate', 'export', 'check'].includes(mode ?? ''))
  throw new Error('Expected generate, export, or check.')

async function run(command: string[], cwd = hostRoot) {
  const process = Bun.spawn(command, { cwd, stdout: 'inherit', stderr: 'inherit' })
  if (await process.exited !== 0) throw new Error(`Command failed: ${command.join(' ')}`)
}

await run(['dotnet', 'build', '--nologo', '-p:BuildSpaOnPublish=false'])
if (mode === 'export' || mode === 'check') {
  await run(['dotnet', 'run', '--no-build', '--no-launch-profile', '--', '--exportopenapijson', 'true'])
  const spec = JSON.parse(readFileSync(document, 'utf8').replace(/^\uFEFF/, ''))
  if (!spec.openapi || !Object.keys(spec.paths ?? {}).length)
    throw new Error('OpenAPI export contains no operations.')
}
if (mode === 'generate' || mode === 'check') {
  await run(['dotnet', 'run', '--no-build', '--no-launch-profile', '--', '--generateclients', 'true'])
  for (const file of ['noCtfClient.ts', 'models/index.ts']) {
    if (!existsSync(resolve(output, file)) || !readFileSync(resolve(output, file), 'utf8').includes('Generated by Microsoft Kiota'))
      throw new Error(`Kiota did not generate ${file}.`)
  }
  // Kiota records a random temporary input location here; it is not client source.
  const lock = resolve(output, 'kiota-lock.json')
  if (existsSync(lock)) unlinkSync(lock)
  if (readdirSync(output).some(name => name.endsWith('.gen.ts')))
    throw new Error('The output still contains a previous generator artifact.')
}
if (mode === 'check') {
  const paths = [document, output].map(path => relative(repositoryRoot, path).replaceAll('\\', '/'))
  await run(['git', 'diff', '--exit-code', 'HEAD', '--', ...paths], repositoryRoot)
  const status = Bun.spawn(['git', 'ls-files', '--others', '--exclude-standard', '--', ...paths], { cwd: repositoryRoot, stdout: 'pipe', stderr: 'inherit' })
  const added = await new Response(status.stdout).text()
  if (await status.exited !== 0 || added.trim())
    throw new Error(`Untracked API artifacts must be committed:\n${added}`)
}
